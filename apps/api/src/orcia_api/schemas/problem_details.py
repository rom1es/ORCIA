"""RFC 9457 Problem Details schema (`application/problem+json`) with W3C `trace_id`."""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field


class ProblemDetails(BaseModel):
    """RFC 9457 Problem Details envelope returned on all ORCIA API errors."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    type: str = Field(
        default="about:blank",
        description="URI reference identifying the problem type.",
    )
    title: str = Field(
        ...,
        description="Short, localized human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        ge=100,
        le=599,
        description="HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        ...,
        description="Localized human-readable explanation specific to this occurrence.",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference identifying the specific occurrence of the problem.",
    )
    error_code: str = Field(
        ...,
        description=(
            "Invariant machine-readable ORCIA error code (e.g. ERR_OBSERVER_MODE_READ_ONLY)."
        ),
    )
    trace_id: str = Field(
        ...,
        min_length=32,
        max_length=32,
        description="32-hex W3C OpenTelemetry trace identifier correlating logs and UI.",
    )
    permission_broker_hint: str | None = Field(
        default=None,
        description="Optional remediation hint from the Permission Broker (AD-6).",
    )
