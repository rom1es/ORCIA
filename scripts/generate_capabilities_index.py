#!/usr/bin/env python3
"""Deterministic generator and `--check` gate for `docs/product/capabilities-index.md`."""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml  # type: ignore[import-untyped]

GENERATED_BANNER = "<!-- Generated by scripts/generate_capabilities_index.py — do not edit -->"
_REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_REGISTRY_PATH = _REPO_ROOT / "docs" / "product" / "capabilities.yaml"
DEFAULT_INDEX_PATH = _REPO_ROOT / "docs" / "product" / "capabilities-index.md"
MAX_TITLE_LEN = 70
_CAP_NUM_RE = re.compile(r"^CAP-(\d+)$")


@dataclass(frozen=True, slots=True)
class CapabilityIndexRow:
    """Single compact row in `docs/product/capabilities-index.md`."""

    cap_id: str
    title: str
    kind: str
    status: str
    verification: str
    ujs: str
    e2e_specs_count: int


def _cap_sort_key(cap_id: str) -> tuple[int, int, str]:
    match = _CAP_NUM_RE.fullmatch(cap_id)
    if match:
        return (0, int(match.group(1)), cap_id)
    return (1, 0, cap_id)


def _sanitize_cell(value: str, *, max_len: int | None = None) -> str:
    cleaned = " ".join(value.replace("|", " / ").split())
    if max_len is not None and len(cleaned) > max_len:
        cleaned = cleaned[: max_len - 1].rstrip() + "…"
    return cleaned or "—"


def _count_e2e_specs(tests: Any) -> int:
    if not isinstance(tests, list):
        return 0
    return sum(
        1
        for item in tests
        if isinstance(item, str)
        and item.strip().replace("\\", "/").startswith("apps/web/e2e/")
        and item.strip().endswith(".spec.ts")
    )


def collect_rows(
    registry_path: Path = DEFAULT_REGISTRY_PATH,
) -> tuple[list[CapabilityIndexRow], int, int]:
    """Load `capabilities.yaml` and return `(sorted_rows, live_count, runtime_count)`."""
    raw = yaml.safe_load(registry_path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or not isinstance(raw.get("capabilities"), list):
        raise ValueError(f"{registry_path}: missing `capabilities` list")

    rows: list[CapabilityIndexRow] = []
    live_count = 0
    runtime_count = 0
    for item in raw["capabilities"]:
        if not isinstance(item, dict):
            continue
        cap_id = _sanitize_cell(str(item.get("id") or ""))
        title = _sanitize_cell(str(item.get("title") or ""), max_len=MAX_TITLE_LEN)
        kind = _sanitize_cell(str(item.get("kind") or ""))
        status = _sanitize_cell(str(item.get("status") or ""))
        verification = _sanitize_cell(str(item.get("verification") or ""))
        raw_ujs = item.get("uj")
        ujs = (
            _sanitize_cell(", ".join(str(u) for u in raw_ujs if str(u).strip()))
            if isinstance(raw_ujs, list) and raw_ujs
            else "—"
        )
        e2e_specs_count = _count_e2e_specs(item.get("tests"))
        if status == "live":
            live_count += 1
        if verification == "runtime":
            runtime_count += 1
        rows.append(
            CapabilityIndexRow(
                cap_id=cap_id,
                title=title,
                kind=kind,
                status=status,
                verification=verification,
                ujs=ujs,
                e2e_specs_count=e2e_specs_count,
            )
        )

    rows.sort(key=lambda r: _cap_sort_key(r.cap_id))
    return rows, live_count, runtime_count


def render_capabilities_index(registry_path: Path = DEFAULT_REGISTRY_PATH) -> str:
    """Render deterministic compact Markdown table for `docs/product/capabilities-index.md`."""
    rows, live_count, runtime_count = collect_rows(registry_path)
    lines = [
        GENERATED_BANNER,
        "",
        "# ORCIA Capabilities Compact Index",
        "",
        (
            f"Total: **{len(rows)}** capabilities (**{live_count}** live, "
            f"**{runtime_count}** runtime) — Grep `CAP-xxx` in "
            "`docs/product/capabilities.yaml` with bounded line read when editing."
        ),
        "",
        "| ID | Title | Kind | Status | Verification | UJs | E2E Specs |",
        "| :--- | :--- | :--- | :--- | :--- | :--- | ---: |",
    ]
    for row in rows:
        lines.append(
            f"| `{row.cap_id}` | {row.title} | {row.kind} | {row.status} | "
            f"{row.verification} | {row.ujs} | {row.e2e_specs_count} |"
        )
    lines.append("")
    return "\n".join(lines)


def run(
    registry_path: Path = DEFAULT_REGISTRY_PATH,
    index_path: Path = DEFAULT_INDEX_PATH,
    *,
    check: bool = False,
) -> int:
    """Generate or verify `docs/product/capabilities-index.md`."""
    expected = render_capabilities_index(registry_path)
    if check:
        if not index_path.is_file():
            print(f"❌ Missing generated capabilities index: {index_path}", file=sys.stderr)
            return 1
        current = index_path.read_text(encoding="utf-8")
        if current != expected:
            print(
                "❌ Capabilities index is out of sync. Run "
                "`.venv/bin/python scripts/generate_capabilities_index.py` or `pnpm site:sync`.",
                file=sys.stderr,
            )
            return 1
        return 0
    index_path.parent.mkdir(parents=True, exist_ok=True)
    index_path.write_text(expected, encoding="utf-8")
    return 0


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint."""
    parser = argparse.ArgumentParser(
        description="Generate or verify docs/product/capabilities-index.md."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if docs/product/capabilities-index.md is out of sync.",
    )
    args = parser.parse_args(argv)
    return run(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
