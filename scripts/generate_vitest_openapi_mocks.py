#!/usr/bin/env python3
"""Zero-dependency deterministic OpenAPI 3.1 -> Vitest mock generator (`T-D2`, Story 32.5).

Usage:
    .venv/bin/python scripts/generate_vitest_openapi_mocks.py
    .venv/bin/python scripts/generate_vitest_openapi_mocks.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from scripts.generate_vitest_openapi_mocks_lib.synthesizer import (  # noqa: E402
    extract_operation_mock_spec,
)

DEFAULT_OPENAPI_PATH = Path("packages/api-client/openapi.json")
DEFAULT_OUTPUT_PATH = Path("apps/web/src/__tests__/setup/generatedOpenApiMocks.ts")
HTTP_METHODS: tuple[str, ...] = ("get", "post", "put", "patch", "delete")


def build_operation_specs(openapi_doc: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """Build deterministic `{ 'METHOD /path': {'status': int, 'body': Any} }` map."""
    schemas = openapi_doc.get("components", {}).get("schemas", {})
    if not isinstance(schemas, dict):
        schemas = {}
    paths = openapi_doc.get("paths", {})
    if not isinstance(paths, dict):
        return {}

    specs: dict[str, dict[str, Any]] = {}
    for path_str in sorted(paths):
        path_item = paths[path_str]
        if not isinstance(path_item, dict):
            continue
        for method in HTTP_METHODS:
            op = path_item.get(method)
            if not isinstance(op, dict):
                continue
            op_key = f"{method.upper()} {path_str}"
            specs[op_key] = extract_operation_mock_spec(op, schemas)
    return specs


def render_typescript_mocks(specs: dict[str, dict[str, Any]]) -> str:
    """Render deterministic TypeScript mock registry and typed builder helpers."""
    op_keys = list(specs.keys())
    lines: list[str] = [
        "/* eslint-disable */",
        "// AUTO-GENERATED BY scripts/generate_vitest_openapi_mocks.py — DO NOT HAND-EDIT.",
        "// Regenerate: .venv/bin/python scripts/generate_vitest_openapi_mocks.py",
        "",
        "export interface GeneratedOpenApiMockSpec<T = unknown> {",
        "  readonly status: number;",
        "  readonly body: T;",
        "}",
        "",
        "export type GeneratedOpenApiOperationKey =",
    ]
    for idx, key in enumerate(op_keys):
        suffix = ";" if idx == len(op_keys) - 1 else ""
        lines.append(f"  | {json.dumps(key)}{suffix}")
    lines.extend(
        [
            "",
            "export const GENERATED_OPENAPI_MOCKS: Record<",
            "  GeneratedOpenApiOperationKey,",
            "  GeneratedOpenApiMockSpec",
            "> = {",
        ]
    )
    for key in op_keys:
        serialized = json.dumps(specs[key], ensure_ascii=False, sort_keys=True)
        low = serialized.lower()
        pragma = (
            " // pragma: allowlist secret"
            if any(kw in low for kw in ("secret", "password", "token", "api_key"))
            else ""
        )
        lines.append(f"  {json.dumps(key)}: {serialized},{pragma}")
    lines.extend(
        [
            "};",
            "",
            "function isPlainObject(value: unknown): value is Record<string, unknown> {",
            '  return typeof value === "object" && value !== null && !Array.isArray(value);',
            "}",
            "",
            "function deepMergeMock(base: unknown, override: unknown): unknown {",
            "  if (override === undefined) return structuredClone(base);",
            "  if (!isPlainObject(base) || !isPlainObject(override)) {",
            "    return structuredClone(override);",
            "  }",
            "  const cloned = structuredClone(base) as Record<string, unknown>;",
            "  const merged: Record<string, unknown> = { ...cloned };",
            "  for (const [k, v] of Object.entries(override)) {",
            "    if (v === undefined) continue;",
            "    merged[k] = k in merged ? deepMergeMock(merged[k], v) : structuredClone(v);",
            "  }",
            "  return merged;",
            "}",
            "",
            "export function buildOpenApiMockPayload<T = Record<string, unknown>>(",
            "  operation: GeneratedOpenApiOperationKey,",
            "  overrides?: Partial<T> | Record<string, unknown> | unknown[],",
            "): T {",
            "  const spec = GENERATED_OPENAPI_MOCKS[operation];",
            "  return deepMergeMock(spec.body, overrides) as T;",
            "}",
            "",
            "export function buildOpenApiMockResponse(",
            "  operation: GeneratedOpenApiOperationKey,",
            "  overrides?: Record<string, unknown> | unknown[],",
            "  init?: { readonly status?: number },",
            "): Response {",
            "  const spec = GENERATED_OPENAPI_MOCKS[operation];",
            "  const status = init?.status ?? spec.status;",
            "  if (status === 204 || (spec.body === null && overrides === undefined)) {",
            "    return new Response(null, { status });",
            "  }",
            "  const payload = deepMergeMock(spec.body, overrides);",
            '  const headers = { "Content-Type": "application/json" };',
            "  return new Response(JSON.stringify(payload), { status, headers });",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generate_or_check(openapi_path: Path, output_path: Path, *, check: bool) -> int:
    """Generate `generatedOpenApiMocks.ts` or assert `0`-diff under `--check`."""
    openapi_doc = json.loads(openapi_path.read_text(encoding="utf-8"))
    specs = build_operation_specs(openapi_doc)
    rendered = render_typescript_mocks(specs)
    if check:
        if not output_path.is_file():
            print(f"FAIL [vitest-openapi-mocks]: missing {output_path.as_posix()}")
            return 1
        current = output_path.read_text(encoding="utf-8")
        if current != rendered:
            print(
                f"FAIL [vitest-openapi-mocks]: {output_path.as_posix()} is out of sync with "
                f"{openapi_path.as_posix()}. "
                "Run: .venv/bin/python scripts/generate_vitest_openapi_mocks.py"
            )
            return 1
        print(f"PASS [vitest-openapi-mocks]: 0-diff ({len(specs)} OpenAPI operations)")
        return 0
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(rendered, encoding="utf-8")
    print(f"GENERATED {output_path.as_posix()} ({len(specs)} OpenAPI operations)")
    return 0


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint."""
    parser = argparse.ArgumentParser(description="Deterministic OpenAPI Vitest mock generator.")
    parser.add_argument("--check", action="store_true", help="Fail if generated file has drift.")
    parser.add_argument("--openapi", type=Path, default=DEFAULT_OPENAPI_PATH)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT_PATH)
    args = parser.parse_args(argv)
    openapi_path = args.openapi if args.openapi.is_absolute() else _REPO_ROOT / args.openapi
    output_path = args.output if args.output.is_absolute() else _REPO_ROOT / args.output
    return generate_or_check(openapi_path, output_path, check=bool(args.check))


if __name__ == "__main__":
    raise SystemExit(main())
