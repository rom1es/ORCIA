#!/usr/bin/env python3
"""Deterministic generator and `--check` gate for `tech-lead-reports/README.md`."""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

GENERATED_BANNER = "<!-- Generated by scripts/generate_tlr_index.py; do not edit manually. -->"
DEFAULT_REPORTS_DIR = (
    Path(__file__).resolve().parents[1] / "docs" / "implementation-artifacts" / "tech-lead-reports"
)
DEFAULT_LEGACY_PATH = Path(__file__).resolve().with_name("tlr_index_legacy.json")

_DATE_LINE_RE = re.compile(r"^\s*-\s*\*\*Date\*\*\s*:\s*(20\d{2}-\d{2}-\d{2})", re.M)
_STORY_LINE_RE = re.compile(r"^\s*-\s*\*\*Story[^:]*\*\*\s*:\s*(.+)$", re.M)
_FILE_DATE_RE = re.compile(r"^(20\d{2}-\d{2}-\d{2})-")
_H1_RE = re.compile(r"^#\s+(.+)$", re.M)


@dataclass(frozen=True, slots=True)
class TlrEntry:
    """Single row in the generated Tech Lead Reports index."""

    date: str
    story: str
    filename: str
    domain: str
    summary: str


def _parse_frontmatter(text: str) -> dict[str, str]:
    if not text.startswith("---\n") and not text.startswith("---\r\n"):
        return {}
    lines = text.splitlines()
    out: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return out
        if ":" not in line or line.lstrip().startswith("#"):
            continue
        key, raw_val = line.split(":", 1)
        val = raw_val.strip()
        if len(val) >= 2 and val[0] == val[-1] and val[0] in ("'", '"'):
            val = val[1:-1]
        out[key.strip()] = val
    return {}


def _sanitize_cell(value: str, *, max_len: int | None = None) -> str:
    cleaned = " ".join(value.replace("|", " / ").split())
    if max_len is not None and len(cleaned) > max_len:
        cleaned = cleaned[: max_len - 1].rstrip() + "…"
    return cleaned or "—"


def _fallback_metadata(path: Path, text: str) -> dict[str, str]:
    date_m = _DATE_LINE_RE.search(text) or _FILE_DATE_RE.match(path.name)
    date = date_m.group(1) if date_m else "2026-01-01"
    story_m = _STORY_LINE_RE.search(text)
    story = story_m.group(1).strip().strip("`") if story_m else "Ad-hoc"
    h1_m = _H1_RE.search(text)
    summary = h1_m.group(1).strip() if h1_m else path.stem
    return {"date": date, "story": story, "domain": "General", "summary": summary}


def _load_legacy(legacy_path: Path | None) -> dict[str, dict[str, str]]:
    if legacy_path is None or not legacy_path.is_file():
        return {}
    raw = json.loads(legacy_path.read_text(encoding="utf-8"))
    return {str(k): dict(v) for k, v in raw.items()}


def collect_entries(
    reports_dir: Path, *, legacy_path: Path | None = DEFAULT_LEGACY_PATH
) -> list[TlrEntry]:
    """Collect index metadata for every valid `*-tech-lead-report.md` in `reports_dir`."""
    legacy = _load_legacy(legacy_path)
    entries: list[TlrEntry] = []
    if not reports_dir.is_dir():
        return entries

    for path in reports_dir.glob("*-tech-lead-report.md"):
        if not path.is_file() or path.name.startswith("_"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        fm = _parse_frontmatter(text)
        leg = legacy.get(path.name, {})
        fb = _fallback_metadata(path, text)

        date = _sanitize_cell(fm.get("date") or leg.get("date") or fb["date"]).strip("*`")
        story = _sanitize_cell(fm.get("story") or leg.get("story") or fb["story"]).strip("`")
        domain = _sanitize_cell(fm.get("domain") or leg.get("domain") or fb["domain"])
        summary = _sanitize_cell(
            fm.get("summary") or leg.get("summary") or fb["summary"], max_len=200
        )
        entries.append(
            TlrEntry(date=date, story=story, filename=path.name, domain=domain, summary=summary)
        )

    entries.sort(key=lambda e: (e.date, e.filename))
    return entries


def render_tlr_index(reports_dir: Path, *, legacy_path: Path | None = DEFAULT_LEGACY_PATH) -> str:
    """Render deterministic Markdown content for `tech-lead-reports/README.md`."""
    entries = collect_entries(reports_dir, legacy_path=legacy_path)
    lines = [
        GENERATED_BANNER,
        "",
        "# Tech Lead Implementation Reports Index",
        "",
        "Sole committed story artifact. Template: "
        "[`../TECH-LEAD-REPORT-TEMPLATE.md`](../TECH-LEAD-REPORT-TEMPLATE.md). "
        "Regenerated by `pnpm site:sync` — never read or edit manually.",
        "",
        "| Date | Story | File | Domain | Summary |",
        "| :--- | :--- | :--- | :--- | :--- |",
    ]
    for e in entries:
        link = f"[`{e.filename}`](./{e.filename})"
        lines.append(f"| **{e.date}** | `{e.story}` | {link} | {e.domain} | {e.summary} |")
    lines.append("")
    return "\n".join(lines)


def run(
    reports_dir: Path = DEFAULT_REPORTS_DIR,
    *,
    legacy_path: Path | None = DEFAULT_LEGACY_PATH,
    check: bool = False,
) -> int:
    """Generate or verify `tech-lead-reports/README.md`."""
    expected = render_tlr_index(reports_dir, legacy_path=legacy_path)
    readme_path = reports_dir / "README.md"
    if check:
        if not readme_path.is_file():
            print(f"❌ Missing generated index: {readme_path}", file=sys.stderr)
            return 1
        current = readme_path.read_text(encoding="utf-8")
        if current != expected:
            print(
                "❌ Tech Lead reports README.md is out of sync. "
                "Run `.venv/bin/python scripts/generate_tlr_index.py` or `pnpm site:sync`.",
                file=sys.stderr,
            )
            return 1
        return 0
    readme_path.write_text(expected, encoding="utf-8")
    return 0


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint."""
    parser = argparse.ArgumentParser(description="Generate or verify tech-lead-reports/README.md.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if README.md is out of sync.")
    args = parser.parse_args(argv)
    return run(check=args.check)


if __name__ == "__main__":
    raise SystemExit(main())
